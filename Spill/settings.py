def load_inappropriate_words():
    candidate_files = [
        BASE_DIR / 'static' / 'inappropriate_words.json',
        BASE_DIR / 'confessions' / 'static' / 'confessions' / 'inappropriate_words.json',
    ]

    for words_file in candidate_files:
        try:
            with words_file.open('r', encoding='utf-8') as file:
                data = json.load(file)
        except (FileNotFoundError, OSError, json.JSONDecodeError):
            continue

        if isinstance(data, dict):
            words = data.get('words', [])
        elif isinstance(data, list):
            words = data
        else:
            words = []

        sanitized_words = []
        for word in words:
            if isinstance(word, str):
                cleaned_word = word.strip()
                if cleaned_word:
                    sanitized_words.append(cleaned_word)

        return tuple(sanitized_words)

    return ()


INAPPROPRIATE_WORDS = load_inappropriate_words()
